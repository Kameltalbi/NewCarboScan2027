import { d } from "@newcarboscan/carbon-engine";
import { exact } from "../format.js";
import type { ActivityLine, ReportData } from "../types.js";

function included(
  input: Omit<ActivityLine, "inclusion" | "resultKgCo2e" | "quantity" | "factorValue"> & {
    quantity: string;
    factorValue: string;
  },
): ActivityLine {
  return {
    ...input,
    inclusion: "included",
    quantity: input.quantity,
    factorValue: input.factorValue,
    resultKgCo2e: exact(d(input.quantity).mul(d(input.factorValue))),
  };
}

